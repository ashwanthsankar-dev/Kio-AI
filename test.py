import os
import sys
import json
import shutil
import argparse
import subprocess
from pathlib import Path
from typing import Dict, Any
import requests

CONFIG_DIR = Path.cwd()
SETTINGS_FILE = CONFIG_DIR / "settings.json"
PROFILES_FILE = CONFIG_DIR / "team_profiles.json"
CLAUDE_MD_FILE = CONFIG_DIR / "CLAUDE.md"

DEFAULT_SETTINGS = {
    "openrouter_api_key": "",
    "personalization_model": "openrouter/free",
    "temperature": 0.2,
    "max_tokens": 4096,
    "timeout_seconds": 30
}

DEFAULT_PROFILE = {
    "team_name": "NoDAY / Kaze AI",
    "lead_developer": "Ashwanth Sankar S",
    "environment": "Windows / PowerShell / Python 3.12",
    "code_standards": [
        "Production-ready, fully typed Python code with explicit type annotations",
        "Comprehensive error handling and clean logging",
        "Modular architecture with single-responsibility functions"
    ]
}


class KioBridge:
    def __init__(self):
        self.settings = self._load_json(SETTINGS_FILE, DEFAULT_SETTINGS)
        self.profile = self._load_json(PROFILES_FILE, DEFAULT_PROFILE)
        self.api_key = self._resolve_api_key()

    @staticmethod
    def _load_json(filepath: Path, default: Dict[str, Any]) -> Dict[str, Any]:
        if filepath.exists():
            try:
                with open(filepath, "r", encoding="utf-8") as f:
                    data = json.load(f)
                    if isinstance(data, dict):
                        merged = default.copy()
                        merged.update(data)
                        return merged
            except Exception as err:
                print(f"⚠️ [Kio Engine] Warning reading {filepath.name}: {err}", file=sys.stderr)
        return default.copy()

    def _resolve_api_key(self) -> str:
        key = self.settings.get("openrouter_api_key") or os.environ.get("OPENROUTER_API_KEY", "")
        return key.strip()

    def sync_claude_md(self, active_context: str) -> None:
        standards_list = "\n".join(f"- {s}" for s in self.profile.get("code_standards", []))
        
        claude_md_content = f"""# KIO Personalization Rules & Team Context
> Auto-generated by Kio Engine for {self.profile.get('lead_developer')} ({self.profile.get('team_name')})

## Environment & Team Info
- **Lead Developer**: {self.profile.get('lead_developer')}
- **Team**: {self.profile.get('team_name')}
- **Target Environment**: {self.profile.get('environment')}

## Project Code Standards
{standards_list}

## Active Task Personalization Context
{active_context}
"""
        try:
            CLAUDE_MD_FILE.write_text(claude_md_content, encoding="utf-8")
            print(f"✨ [Kio Engine] Synced live context to {CLAUDE_MD_FILE.name}")
        except Exception as err:
            print(f"⚠️ [Kio Engine] Failed to sync CLAUDE.md: {err}", file=sys.stderr)

    def personalize(self, raw_prompt: str) -> str:
        if not self.api_key:
            print("⚠️ [Kio Engine] OPENROUTER_API_KEY missing. Bypassing personalization stage.")
            self.sync_claude_md("Standard execution without LLM prompt pre-processing.")
            return raw_prompt

        print(f"🤖 [Kio Engine] Enriching prompt via model [{self.settings['personalization_model']}]...")

        system_instruction = (
            f"You are the Kio Personalization Agent for Lead Developer {self.profile.get('lead_developer')} "
            f"({self.profile.get('team_name')}). Refine the user's task prompt into a structured, explicit, "
            f"unambiguous set of technical specifications suitable for direct automated CLI execution on "
            f"{self.profile.get('environment')}. Return ONLY the finalized enriched prompt without conversational filler."
        )

        url = "https://openrouter.ai/api/v1/chat/completions"
        headers = {
            "Authorization": f"Bearer {self.api_key}",
            "HTTP-Referer": "https://localhost",
            "X-Title": "Kio Claude Code Integration Bridge",
            "Content-Type": "application/json"
        }
        payload = {
            "model": self.settings["personalization_model"],
            "messages": [
                {"role": "system", "content": system_instruction},
                {"role": "user", "content": raw_prompt}
            ],
            "temperature": self.settings.get("temperature", 0.2),
            "max_tokens": self.settings.get("max_tokens", 4096)
        }

        try:
            response = requests.post(
                url, 
                headers=headers, 
                json=payload, 
                timeout=self.settings.get("timeout_seconds", 30)
            )
            response.raise_for_status()
            data = response.json()
            enriched_prompt = data["choices"][0]["message"]["content"].strip()

            self.sync_claude_md(enriched_prompt)
            return enriched_prompt

        except Exception as err:
            print(f"⚠️ [Kio Engine] Personalization API call failed ({err}). Falling back to raw prompt.", file=sys.stderr)
            self.sync_claude_md(f"Raw prompt execution fallback: {raw_prompt}")
            return raw_prompt

    def run_claude_code(self, prompt: str, print_only: bool = False) -> int:
        claude_bin = shutil.which("claude") or shutil.which("claude.cmd")

        if print_only:
            print("\n" + "=" * 60)
            print("--- ENRICHED PROMPT OUTPUT (DRY RUN) ---")
            print("=" * 60)
            print(prompt)
            print("=" * 60)
            return 0

        if not claude_bin:
            print("\n❌ [Error] Official 'claude' CLI executable not found in PATH.", file=sys.stderr)
            print("   Please install via npm: npm install -g @anthropic-ai/claude-code\n", file=sys.stderr)
            return 1

        print("\n🚀 [Kio Engine] Handing off task to official Claude Code CLI...\n" + "=" * 60 + "\n")

        try:
            process = subprocess.run([claude_bin, "-p", prompt], check=False)
            return process.returncode
        except KeyboardInterrupt:
            print("\n⚡ Execution cancelled by user.")
            return 130
        except Exception as err:
            print(f"\n❌ [Error] Subprocess execution failed: {err}", file=sys.stderr)
            return 1


def main():
    parser = argparse.ArgumentParser(
        description="Kio Personalization Engine — Claude Code CLI Integration Bridge"
    )
    parser.add_argument(
        "prompt", 
        nargs="*", 
        help="Task prompt for Claude Code CLI"
    )
    parser.add_argument(
        "--dry-run", "-d", 
        action="store_true", 
        help="Print the personalized prompt without launching Claude Code"
    )

    args = parser.parse_args()

    if not args.prompt:
        parser.print_help()
        sys.exit(1)

    raw_prompt = " ".join(args.prompt)
    
    bridge = KioBridge()
    enriched_prompt = bridge.personalize(raw_prompt)
    exit_code = bridge.run_claude_code(enriched_prompt, print_only=args.dry_run)
    
    sys.exit(exit_code)


if __name__ == "__main__":
    main()